void variable() {
  if (nextToken == TOK_IDENT) {
    output("IDENTIFIER");
    string var_name = yytext;
    string var_type = "";
    lex();
    
    if (nextToken == TOK_COLON) {
      output("COLON");
      lex();
      if (nextToken == TOK_INTEGER || nextToken == TOK_REAL) {
        output("TYPE");
        var_type = yytext;
      }
      else {
        throw "10: error in type";
      }
      lex();
      if (nextToken == TOK_SEMICOLON) {
        output("SEMICOLON");
        
      }
      else {
        throw "14: ';' expected";
      }
      output_variable(var_name, var_type);
      if (!symbolTable.insert(var_name).second) {
        throw "101: identifier declared twice";
      }
      lex();
      if (nextToken == TOK_IDENT) {
          variable();
      }
    }
    else {
      throw "5: ':' expected";
    }
  }
  else {
    throw "2: identifier expected";
  }                  
}

StatementNode* statement() {
  output("STATEMENT");
  StatementNode* newStatementNode = nullptr;

  
  if (!first_of_statement){ 
    throw "900: illegal type of statement";
  }
  if (nextToken == TOK_WRITE) {
    
    newStatementNode = write(); 
  
    // write();
  }
  else if (nextToken == TOK_IDENT) {
    newStatementNode = assignment();
  } 
  else if (nextToken == TOK_BEGIN) {
    newStatementNode = compound();
    // compound();
    
  }
  else if (nextToken == TOK_READ) {
    newStatementNode = read();
  }
  else if (nextToken == TOK_IF) {
    newStatementNode = if_statement();
  }
  else if (nextToken == TOK_WHILE) {
    newStatementNode = while_statement();
  }
  return newStatementNode;
} 

ExprNode* expression() {
  output("EXPRESSION");
  cout << psp() << "enter <expression>" << endl;
  
  ExprNode* newExprNode = new ExprNode(level);
  ++level;
  newExprNode->firstSimpleExpr = simple_expression();
 
  if (first_of_expression()){ 
    if (nextToken == TOK_EQUALTO) {
      output("EQUALTO");
      output_string_lit();
    }
    else if (nextToken == TOK_GREATERTHAN) {
      output("GREATERTHAN");
      output_string_lit();
    }
    else if (nextToken == TOK_LESSTHAN) {
      output("LESSTHAN");
      output_string_lit();
    }
    else if (nextToken == TOK_NOTEQUALTO) {
      output("NOTEQUALTO");
      output_string_lit();
      
    }
    newExprNode->restSimpleExprOps.push_back(nextToken);
     
         
    lex();
    // if (first_of_simple_expression()) {
    if (first_of_factor()) {
    
         
      newExprNode->restSimpleExprs.push_back(simple_expression());
      
    }
    else {
       throw "144: illegal type of expression";
    }
  }
  
  --level;
  cout << psp() << "exit <expression>" << endl;
  return newExprNode;
}

SimpleExprNode* simple_expression() {
  output("SIMPLE_EXP");
  cout << psp() << "enter <simple_exp>" << endl;
  
  bool isValid = true;
  SimpleExprNode* newSimpleExprNode = new SimpleExprNode(level);
  ++level;
  newSimpleExprNode->firstTerm = term();
  while (isValid) {
      if (!first_of_factor()) {
        throw "901: illegal type of simple expression";
      }
      //term();
      if (first_of_simple_expression()) {
        if (nextToken == TOK_PLUS) {
          output("PLUS");
          output_string_lit();
          newSimpleExprNode->restTermOps.push_back(nextToken);
          lex();
          newSimpleExprNode->restTerms.push_back(term());
        }
        else if (nextToken == TOK_MINUS) {
          output("MINUS");
          output_string_lit();
          newSimpleExprNode->restTermOps.push_back(nextToken);
          lex();
          newSimpleExprNode->restTerms.push_back(term());
        }
        else if (nextToken == TOK_OR) {
          output("OR");
          output_string_lit();
          newSimpleExprNode->restTermOps.push_back(nextToken);
          lex();
          newSimpleExprNode->restTerms.push_back(term());
        }
        
      }
      else {
       
        isValid = false;
      }
    }
  --level;
  cout << psp() << "exit <simple_exp>" << endl;
  return newSimpleExprNode;
}

TermNode* term() {
  output("TERM");
  cout << psp() << "enter <term>" << endl;
  
  TermNode* newTermNode = new TermNode(level);
  ++level;
  bool isValid = true;
  newTermNode->firstFactor = factor();
  
  // if (!first_of_term()) {
  //   isValid = false;
  // }
  while (isValid) {
    if (!first_of_factor()) {
       throw "902: illegal type of term";
    }
    // factor();
    lex();
    if (first_of_term()) {
      if (nextToken == TOK_MULTIPLY) {
        output("MULTIPLY");
        output_string_lit();
        // lex();
        newTermNode->restFactorOps.push_back(nextToken);
        lex();
        newTermNode->restFactors.push_back(factor());
      }
      else if (nextToken == TOK_DIVIDE) {
        output("DIVIDE");
        output_string_lit();
        // lex();
        newTermNode->restFactorOps.push_back(nextToken);
        lex();
        newTermNode->restFactors.push_back(factor());
      }
      else if (nextToken == TOK_AND) {
        output("AND");
        output_string_lit();
        // lex();
        newTermNode->restFactorOps.push_back(nextToken);
        lex();
        newTermNode->restFactors.push_back(factor());
      }
      if (!first_of_factor()) {
        throw "902: illegal type of term";
      }
    } else {
      isValid = false;
    }
  }
  --level;
  cout << psp() << "exit <term>" << endl;
  return newTermNode;
}

FactorNode* factor() {
  output("FACTOR");
  cout << psp() << "enter <factor>" << endl;
 
  if (!first_of_factor){ 
    throw "903: illegal type of factor";
  }
 
  FactorNode* newFactorNode = nullptr;
  ++level;
  if (nextToken == TOK_INTLIT) {
    output("INTLIT");
    -- level;
    newFactorNode = new IntLitNode(level, atoi(yytext));
    ++ level;
    // lex(); // random lex
    output_string_lit();

    
  }
  else if (nextToken == TOK_FLOATLIT) {
    output("FLOATLIT");
    -- level;
    newFactorNode = new FloatLitNode(level, atof(yytext));
    ++ level;
    // lex(); // random lex
    output_string_lit();
    
  }
  else if (nextToken == TOK_IDENT) {
    output("IDENTIFIER");
    -- level;
    newFactorNode = new IdNode(level, string(yytext));
    ++ level;
  //  lex(); // random lex  
    output_string_lit();
    if (symbolTable.find(yytext) == symbolTable.end()) {
      throw "104: identifier not declared";
    }
    
  }
  else if (nextToken == TOK_OPENPAREN) {
    output("OPENPAREN");
    output_string_lit();
    lex();
    -- level;
    int old_level = level;
    ++ level;
    newFactorNode = new NestedExprNode(old_level, expression());
    
    
    if (nextToken == TOK_CLOSEPAREN) {
      output("CLOSEPAREN");
    }
    else {
      throw "4: ')' expected";
    }
  }
  else if (nextToken == TOK_NOT) {
    output("NOT");
    output_string_lit();
    lex();
    -- level;
    int old_level = level;
    ++ level;
    newFactorNode = new NotNode(old_level, factor());
    
   
    // factor();
    
  }
  else if (nextToken == TOK_MINUS) {
    output("MINUS");
    output_string_lit();
    lex();
    // factor();
    -- level;
    int old_level = level;
    ++ level;
    newFactorNode = new MinusNode(old_level, factor());
   
    
  }
  --level;
  cout << psp() << "exit <factor>" << endl;
  return newFactorNode;
}

