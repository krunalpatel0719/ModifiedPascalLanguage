CompoundStatementNode* compound() {
  if (!first_of_compound) {
    throw "17: 'BEGIN' expected";
  }
  if (nextToken == TOK_BEGIN) {
      output("BEGIN");
      lex();   
  }
  cout << psp() << "enter <compound_stmt>" << endl;
  
  CompoundStatementNode* newCompoundStatementNode = nullptr;
  newCompoundStatementNode = new CompoundStatementNode(level);
  ++level;
  while (first_of_statement()) {
    
    newCompoundStatementNode->statements.push_back(statement());
  
    // statement();
    if (nextToken == TOK_SEMICOLON) {
      output("SEMICOLON");
      lex();
    }
    else {
      break;
    }
  }
  --level;
  if (nextToken == TOK_END) {
    // --level;
    output("END");
    lex();
    // ++level;
  }
  else {
    throw "13: 'END' expected";
  }

  
  
  cout << psp() << "exit <compound_stmt>" << endl;
  return newCompoundStatementNode;
}

